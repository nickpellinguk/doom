#!/usr/bin/env python3
"""The game's first rules (docs/tube_master.md H8): pickups and nukage,
the panel's numbers from them. The spec the Tube host's gm_tick
(src/tube/hgame.s) reproduces byte for byte; test_game.py holds it to it.

DOOM's own rules (p_inter.c, p_spec.c), in our units:

  touch     a pickup is touched when |dx| < 36 and |dy| < 36 (its radius
            20 + the player's 16; the raws are world units from the map
            centre). Tested once a frame, in the table's order.
  stimpack  +10 health, to 100 -- not taken at 100 or more
  medikit   +25 health, to 100 -- not taken at 100 or more
  potion    +1 health, to 200 (always taken)
  helmet    +1 armour, to 200; armour type 1 if none (always taken)
  green     armour 100, type 1 -- not taken at 100 or more
  blue      armour 200, type 2 -- not taken at 200 or more
  nukage    a sector with special 7 hurts 5 every 32 tics: here a clock of
            fields (50 Hz) wraps every 46 (0.92 s, 32 tics at 35 Hz), and
            each wrap while the player's subsector is nukage is a hit.
            Armour type 1 saves damage // 3, type 2 damage // 2 (no more
            than the armour left, which then loses its type); health
            stops at 0 (no death yet).

A picked-up object is GONE: the engine stops staging it (gone, by its
index in e1m1.fp_objects; sprite_ref.Staging takes the same set).
"""
TOUCH = 36
PERIOD = 46                             # fields a nukage hit (32 tics)
NUKAGE = {7: 5}                         # sector special -> damage
STIM, MEDI, POTION, HELMET, GREEN, BLUE = range(6)
TYPES = {2011: STIM, 2012: MEDI, 2014: POTION, 2015: HELMET, 2018: GREEN, 2019: BLUE}
AMMO = 50                               # (no ammo pickups or firing yet)


def pickups():
    """[(object index, raw x, raw y, pickup type)], fp_objects order."""
    import e1m1 as dw
    return [(i, o['rx'], o['ry'], TYPES[o['type']])
            for i, o in enumerate(dw.fp_objects) if o['type'] in TYPES]


def damaging():
    """{subsector: damage} for the nukage subsectors."""
    import e1m1 as dw
    out = {}
    for ss, (cnt, first) in enumerate(dw.fp_ssectors):
        sec = dw.sectors[dw.fp_segs_vwh[first][1]]
        if sec[5] in NUKAGE:
            out[ss] = NUKAGE[sec[5]]
    return out


class Game:
    def __init__(self):
        self.health, self.armor, self.atype = 100, 0, 0
        self.clock = 0
        self.gone = set()
        self.table = pickups()
        self.dmg = damaging()

    def values(self):
        """The panel's fields: ammo, health, armour."""
        return (AMMO, self.health, self.armor)

    def tick(self, rx, ry, ss, fields):
        """One frame: the player at raws (rx, ry) in subsector ss, fields
        (50 Hz) since the last frame."""
        for i, x, y, t in self.table:
            if i not in self.gone and abs(rx - x) < TOUCH and abs(ry - y) < TOUCH:
                if self.give(t):
                    self.gone.add(i)
        self.clock += fields
        while self.clock >= PERIOD:
            self.clock -= PERIOD
            if ss in self.dmg and self.health > 0:
                self.damage(self.dmg[ss])

    def give(self, t):
        if t in (STIM, MEDI):
            if self.health >= 100:
                return False
            self.health = min(100, self.health + (10 if t == STIM else 25))
        elif t == POTION:
            self.health = min(200, self.health + 1)
        elif t == HELMET:
            self.armor = min(200, self.armor + 1)
            if not self.atype:
                self.atype = 1
        else:
            top = 100 if t == GREEN else 200
            if self.armor >= top:
                return False
            self.armor, self.atype = top, 1 if t == GREEN else 2
        return True

    def damage(self, d):
        if self.atype:
            saved = d // 3 if self.atype == 1 else d // 2
            if self.armor <= saved:
                saved, self.atype = self.armor, 0
            self.armor -= saved
            d -= saved
        self.health = max(0, self.health - d)


TAB = __import__('os').path.join(__import__('os').path.dirname(__import__('os').path.abspath(__file__)),
                                 'src', 'tube', 'hgame_tab.s')


def tab_source():
    """src/tube/hgame_tab.s: the pickups (object, raws, type) and the
    nukage subsectors' bitmap, for gm_tick."""
    import e1m1 as dw
    t = pickups()
    d = damaging()
    assert set(d.values()) == {5}, 'gm_tick hits 5 (NUKAGE)'
    bits = [0] * ((len(dw.fp_ssectors) + 7) // 8)
    for ss in d:
        bits[ss >> 3] |= 1 << (ss & 7)
    L = ['; GENERATED by game_ref.py -- the pickups and the nukage for the',
         '; Tube host\'s gm_tick (src/tube/hgame.s, H8). Do not edit.',
         f'GM_NPK = {len(t)}', f'GM_PERIOD = {PERIOD}', f'GM_TOUCH = {TOUCH}']
    for name, f in (('gm_po', lambda e: e[0]), ('gm_pt', lambda e: e[3]),
                    ('gm_pxl', lambda e: e[1] & 0xFF), ('gm_pxh', lambda e: e[1] >> 8 & 0xFF),
                    ('gm_pyl', lambda e: e[2] & 0xFF), ('gm_pyh', lambda e: e[2] >> 8 & 0xFF)):
        L.append(f'{name}:  .byte ' + ', '.join(str(f(e)) for e in t))
    L.append('gm_nuke: .byte ' + ', '.join(f'${b:02X}' for b in bits))
    return '\n'.join(L) + '\n'


if __name__ == '__main__':
    open(TAB, 'w').write(tab_source())
    t = pickups()
    print(f'{len(t)} pickups, nukage subsectors {sorted(damaging())}; wrote {TAB}')
