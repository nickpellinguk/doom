#!/usr/bin/env python3
"""Sound effects on the SN76489 (docs/tube_master.md H9), the Tube build:
the spec src/tube/hsfx.s reproduces chip byte for chip byte.

Four DOOM sounds, made on the chip rather than sampled:
  PICKUP  DSITEMUP's bloop: a fast rising tone (C5 up to E6), fading
  PAIN    DSPLPAIN: a white-noise bark over a falling tone
  GRIND   DSDOROPN / DSPSTART: a low noise rumble with a buzzing tone
          under it, wobbling, then fading -- a door or lift setting off
  THUD    DSPSTOP / the door's end: a short low knock
gm_tick asks for them: PICKUP when a pickup is taken, PAIN on a nukage
hit, GRIND when a mover sets off (its state goes from waiting to moving),
THUD when one arrives (moving to waiting).

An effect is a list of FRAMES, one a 50 Hz tick: the tone's period N (the
chip's 10 bits: 125000 / N Hz) or None, its attenuation, the noise's
control (0-7) or None, its attenuation. It takes two channels while it
plays: SOUND 3's tone (register $80) and the noise (SOUND 0, $E0) -- the
music's bass voice and its (rare) percussion. Each tick, AFTER the music's
own writes, the effect's frame is written: the tone's period and
attenuation every tick (so whatever the music wrote to that channel this
tick is overwritten microseconds later), the noise control only when it
changes (writing it resets the noise), its attenuation every tick. When
the frames run out both channels are silenced and the music's remembered
attenuations for them (Player.att, the resident ch_att) are spoiled ($FF):
the music writes its own levels again on its next tick, and its own next
note restores the tone's pitch.

A request (Sfx.request, hsfx.s sfx_start: the main loop) is taken by the
next tick; it replaces what is playing only if its PRIORITY is at least
that effect's (PAIN 3, PICKUP 2, GRIND / THUD 1).
"""
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
TAB = os.path.join(ROOT, 'src', 'tube', 'hsfx_tab.s')

PICKUP, PAIN, GRIND, THUD = range(4)
PRIO = [2, 3, 1, 1]
WHITE_LOW = 6                           # noise control: white, N/2048
WHITE_MID = 5                           #  white, N/1024


def _effects():
    E = {}
    E[PICKUP] = [(n, a, None, 15) for n, a in
                 ((239, 1), (190, 1), (159, 2), (119, 3), (95, 5), (95, 9), (95, 13))]
    E[PAIN] = [(350 + 35 * i, min(15, 3 + i // 2), WHITE_MID, min(15, 2 + i))
               for i in range(11)]
    g = []
    for i in range(36):
        w = (0, 2, 1, 3)[i % 4]
        fade = max(0, i - 29) * 2
        g.append((1000, min(15, 9 + (i & 1) * 2 + fade), WHITE_LOW, min(15, 3 + w + fade)))
    E[GRIND] = g
    E[THUD] = [(1023, min(15, 3 + 3 * i), WHITE_LOW, min(15, 1 + 3 * i)) for i in range(6)]
    return E


EFFECTS = _effects()
TONE, NOISE = 3, 0                      # the channels (SOUND numbers)


class Sfx:
    """The 6502's state: the effect playing (None), its frame, a request."""

    def __init__(self):
        self.cur = None
        self.i = 0
        self.req = None
        self.nctl = None                # the noise control last written

    def request(self, e):
        """sfx_start: taken by the next tick if it outranks what plays."""
        if self.cur is None or PRIO[e] >= PRIO[self.cur]:
            self.req = e

    def tick(self, player):
        """After player.tick() in the same IRQ: the effect's chip bytes."""
        out = []
        if self.req is not None:
            self.cur, self.i, self.req, self.nctl = self.req, 0, None, None
        if self.cur is None:
            return out
        fr = EFFECTS[self.cur]
        if self.i == len(fr):           # done: silence, the music's back
            out += [0x9F, 0xFF]
            player.att[TONE] = player.att[NOISE] = 0xFF
            self.cur = None
            return out
        n, ta, nc, na = fr[self.i]
        self.i += 1
        if n is None:
            out.append(0x9F)
        else:
            out += [0x80 | (n & 15), n >> 4, 0x90 | ta]
        if nc is not None and nc != self.nctl:
            out.append(0xE0 | nc)
            self.nctl = nc
        out.append(0xF0 | (na if nc is not None else 15))
        return out


def tab_source():
    """src/tube/hsfx_tab.s: per effect its frames' address and priority;
    a frame is 4 bytes -- $80 | N lo, N hi (bit 7: no tone), tone att << 4
    | noise att, noise control ($FF: none) -- the last followed by $FF."""
    import master_music
    labs = master_music.build()[3]
    L = ['; GENERATED by master_sfx.py -- the sound effects for the Tube host',
         '; (src/tube/hsfx.s, H9). Do not edit.',
         f'SFX_N = {len(EFFECTS)}',
         f'MUS_CH_ATT = ${labs["ch_att"]:04X}           ; the resident player\'s attenuations',
         'sx_lo:  .byte ' + ', '.join(f'<sx_e{e}' for e in sorted(EFFECTS)),
         'sx_hi:  .byte ' + ', '.join(f'>sx_e{e}' for e in sorted(EFFECTS)),
         'sx_pri: .byte ' + ', '.join(str(PRIO[e]) for e in sorted(EFFECTS))]
    for e in sorted(EFFECTS):
        L.append(f'sx_e{e}:')
        for n, ta, nc, na in EFFECTS[e]:
            b = (0x80, 0x80) if n is None else (0x80 | (n & 15), n >> 4)
            L.append(f'        .byte ${b[0]:02X}, ${b[1]:02X}, ${ta << 4 | na:02X}, '
                     f'${(0xFF if nc is None else nc):02X}')
        L.append('        .byte $FF')
    return '\n'.join(L) + '\n'


if __name__ == '__main__':
    open(TAB, 'w').write(tab_source())
    print('wrote', TAB, {e: len(f) for e, f in EFFECTS.items()})
